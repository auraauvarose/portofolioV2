)

for entry in "${FONTS[@]}"; do
  read -r fam weight path <<< "$entry"
  out="$DIR/${fam}-${weight}.woff2"
  echo "Downloading ${fam} ${weight}..."
  curl -sL "$BASE/$path.woff2" -o "$out"
  echo "  -> $out ($(stat -c%s "$out" 2>/dev/null || echo '?') bytes)"
done

echo "Download complete."
